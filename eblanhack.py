class VisualSystem:
    def __init__(self, mem: MemoryManager):
        self.mem = mem
        self.glow_enabled = False
        self.radar_enabled = False
        self.overlay_enabled = False
        self.glow_color = (1.0, 0.0, 0.0, 1.0)
        self.glow_style = 1
        self.overlay_opacity = 0.7
        self.overlay_color = (0, 255, 0)
        logger.info("VisualSystem initialized")
    
    def glow_esp(self, enemies: List[Player], color: Tuple[float, float, float, float] = None) -> bool:
        if not self.glow_enabled:
            return False
        gm = self.mem.get_glow_manager()
        if not gm or not enemies:
            return False
        if color is None:
            color = self.glow_color
        for enemy in enemies:
            idx = self.mem.read_int(enemy.address + 0x10428)
            if idx < 0:
                continue
            go = gm + (idx * 0x38)
            r, g, b, a = color
            self.mem.write_float(go + 0x4, r)
            self.mem.write_float(go + 0x8, g)
            self.mem.write_float(go + 0xC, b)
            self.mem.write_float(go + 0x10, a)
            self.mem.write_int(go + 0x24, 1)
            self.mem.write_int(go + 0x28, self.glow_style)
        return True
    
    def radar_hack(self) -> bool:
        if not self.radar_enabled:
            return False
        if not self.mem.base_address:
            return False
        self.mem.write_int(self.mem.base_address + 0x17C2B40, 1)
        return True

