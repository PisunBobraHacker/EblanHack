class SecurityManager:
    """Менеджер безопасности с анти-детект и анти-отладкой"""
    
    def __init__(self):
        self._checks = {}
        self._passed = False
        self._vm_checked = False
        self._sandbox_checked = False
        self._debugger_checked = False
        self._integrity_checked = False
        logger.security("SecurityManager initialized")
    
    def check_vm(self) -> bool:
        """Проверка на виртуальную машину"""
        if self._vm_checked:
            return self._checks.get("vm", False)
        
        try:
            import wmi
            c = wmi.WMI()
            for system in c.Win32_ComputerSystem():
                model = system.Model.lower()
                if any(x in model for x in ['virtualbox', 'vmware', 'qemu', 'kvm', 'hyper-v', 'parallels']):
                    logger.security(f"VM detected: {system.Model}")
                    self._checks["vm"] = False
                    self._vm_checked = True
                    return False
        except:
            pass
        
        # Проверка через реестр
        try:
            keys = [
                r"SYSTEM\CurrentControlSet\Control\SystemInformation",
                r"HARDWARE\ACPI\DSDT",
                r"HARDWARE\ACPI\FADT",
                r"SYSTEM\CurrentControlSet\Enum\PCI",
            ]
            for key in keys:
                try:
                    reg = winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, key)
                    value = winreg.QueryValueEx(reg, "SystemManufacturer")[0]
                    if "Virtual" in value:
                        logger.security(f"VM detected via registry: {value}")
                        self._checks["vm"] = False
                        self._vm_checked = True
                        return False
                except:
                    pass
        except:
            pass
        
        self._checks["vm"] = True
        self._vm_checked = True
        return True
    
    def check_sandbox(self) -> bool:
        """Проверка на песочницу"""
        if self._sandbox_checked:
            return self._checks.get("sandbox", False)
        
        # Проверка размера диска
        try:
            import ctypes
            disk_free = ctypes.c_ulonglong()
            ctypes.windll.kernel32.GetDiskFreeSpaceExW(
                ctypes.c_wchar_p("C:\\"),
                None,
                None,
                ctypes.byref(disk_free)
            )
            if disk_free.value < 10 * 1024 * 1024 * 1024:
                logger.security(f"Sandbox detected: small disk space {disk_free.value / (1024**3):.1f}GB")
                self._checks["sandbox"] = False
                self._sandbox_checked = True
                return False
        except:
            pass
        
        # Проверка времени работы
        try:
            uptime = time.time() - win32api.GetTickCount() / 1000
            if uptime < 300:
                logger.security(f"Sandbox detected: short uptime {uptime:.1f}s")
                self._checks["sandbox"] = False
                self._sandbox_checked = True
                return False
        except:
            pass
        
        # Проверка количества процессов
        try:
            import psutil
            if len(psutil.process_iter()) < 30:
                logger.security("Sandbox detected: low process count")
                self._checks["sandbox"] = False
                self._sandbox_checked = True
                return False
        except:
            pass
        
        self._checks["sandbox"] = True
        self._sandbox_checked = True
        return True
    
    def check_debugger(self) -> bool:
        """Проверка на отладчик"""
        if self._debugger_checked:
            return self._checks.get("debugger", False)
        
        # IsDebuggerPresent
        try:
            if ctypes.windll.kernel32.IsDebuggerPresent():
                logger.security("Debugger detected: IsDebuggerPresent")
                self._checks["debugger"] = False
                self._debugger_checked = True
                return False
        except:
            pass
        
        # NtQueryInformationProcess
        try:
            from ctypes import wintypes
            class PROCESS_BASIC_INFORMATION(ctypes.Structure):
                _fields_ = [
                    ("ExitStatus", wintypes.LONG),
                    ("PebBaseAddress", ctypes.c_void_p),
                    ("AffinityMask", ctypes.c_void_p),
                    ("BasePriority", wintypes.LONG),
                    ("UniqueProcessId", ctypes.c_void_p),
                    ("InheritedFromUniqueProcessId", ctypes.c_void_p),
                ]
            
            ntdll = ctypes.WinDLL('ntdll')
            pbi = PROCESS_BASIC_INFORMATION()
            return_len = wintypes.ULONG()
            
            status = ntdll.NtQueryInformationProcess(
                ctypes.windll.kernel32.GetCurrentProcess(),
                0,
                ctypes.byref(pbi),
                ctypes.sizeof(pbi),
                ctypes.byref(return_len)
            )
            
            if pbi.PebBaseAddress:
                ptr = ctypes.cast(pbi.PebBaseAddress, ctypes.POINTER(ctypes.c_byte))
                if ptr and ptr[0x2] != 0:
                    logger.security("Debugger detected: PEB BeingDebugged flag")
                    self._checks["debugger"] = False
                    self._debugger_checked = True
                    return False
        except:
            pass
        
        # Проверка времени выполнения
        try:
            import timeit
            start = time.perf_counter()
            for _ in range(10000):
                pass
            elapsed = time.perf_counter() - start
            if elapsed > 0.1:
                logger.security("Debugger detected: slow execution")
                self._checks["debugger"] = False
                self._debugger_checked = True
                return False
        except:
            pass
        
        self._checks["debugger"] = True
        self._debugger_checked = True
        return True
    
    def check_integrity(self) -> bool:
        """Проверка целостности кода"""
        if self._integrity_checked:
            return self._checks.get("integrity", False)
        
        # Проверка файла на диске
        try:
            import hashlib
            with open(__file__, 'rb') as f:
                content = f.read()
                hash_value = hashlib.sha256(content).hexdigest()
                # Здесь можно сравнить с эталонным хешем
                self._checks["integrity"] = True
                self._integrity_checked = True
                return True
        except:
            pass
        
        self._checks["integrity"] = False
        self._integrity_checked = True
        return False
    
    def run_all_checks(self) -> bool:
        """Запуск всех проверок безопасности"""
        checks = [
            ("VM", self.check_vm),
            ("Sandbox", self.check_sandbox),
            ("Debugger", self.check_debugger),
            ("Integrity", self.check_integrity),
        ]
        
        for name, check in checks:
            if not check():
                logger.critical(f"Security check failed: {name}")
                self._passed = False
                return False
        
        self._passed = True
        logger.success("All security checks passed")
        return True
    
    def is_secure(self) -> bool:
        return self._passed

