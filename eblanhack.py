    def _bot_loop(self):
        """Основной цикл бота"""
        sct = mss.mss()
        monitor = {"top": 0, "left": 0, "width": ScreenConstants.WIDTH, "height": ScreenConstants.HEIGHT}
        fps_counter = 0
        last_time = time.time()
        last_stats_update = time.time()
        
        while self.bot.is_running:
            try:
                # Захват экрана
                screenshot = sct.grab(monitor)
                frame = np.array(screenshot)
                frame = cv2.cvtColor(frame, cv2.COLOR_BGRA2BGR)
                
                # Обновление бота
                self.bot.update(frame)
                
                # Обновление FPS
                fps_counter += 1
                current_time = time.time()
                if current_time - last_time >= 1:
                    self.fps_label.configure(text=f"FPS: {fps_counter}")
                    fps_counter = 0
                    last_time = current_time
                
                # Обновление статистики
                if current_time - last_stats_update >= 0.5:
                    stats = self.bot.get_stats()
                    self.targets_label.configure(text=f"Targets: {stats['targets']}")
                    self.shots_label.configure(text=f"Shots: {stats['shots']}")
                    
                    # Обновление вкладки STATS
                    self.stats_labels["FPS"].configure(text=str(stats['fps']))
                    self.stats_labels["Targets"].configure(text=str(stats['targets']))
                    self.stats_labels["Shots"].configure(text=str(stats['shots']))
                    self.stats_labels["BunnyHops"].configure(text=str(stats['bhops']))
                    self.stats_labels["Teleports"].configure(text=str(stats['teleports']))
                    self.stats_labels["Kills"].configure(text=str(stats['kills']))
                    self.stats_labels["Damage"].configure(text=str(stats['damage']))
                    self.stats_labels["Accuracy"].configure(text=f"{stats['accuracy']:.1f}%")
                    self.stats_labels["Uptime"].configure(text=stats['elapsed_str'])
                    self.stats_labels["Status"].configure(
                        text="AIMING" if self.bot.is_aiming else "SHOOTING" if self.bot.is_shooting else "ACTIVE"
                    )
                    
                    last_stats_update = current_time
                
                time.sleep(0.001)
            except Exception as e:
                logger.error(f"Bot loop error: {e}")
                time.sleep(0.1)
    
