class YOLOAimbot:
    def __init__(self, model_path: str):
        self.model_path = model_path
        self.model = None
        self.fov = 300
        self.speed = 0.25
        self.confidence = 0.5
        self.target_classes = [0, 1]
        self._frame_skip = 2
        self._frame_counter = 0
        self._last_detection = []
        self._load_model()
        logger.info("YOLOAimbot initialized")
    
    def _load_model(self):
        try:
            if os.path.exists(self.model_path):
                self.model = YOLO(self.model_path)
                logger.success(f"YOLO loaded: {self.model_path}")
            else:
                logger.warning(f"YOLO model not found: {self.model_path}")
        except Exception as e:
            logger.error(f"YOLO load error: {e}")
    
    def detect(self, frame: np.ndarray) -> List[Dict]:
        self._frame_counter += 1
        if self._frame_counter % self._frame_skip != 0:
            return self._last_detection
        if not self.model:
            return []
        try:
            results = self.model(frame, conf=self.confidence, verbose=False)
            players = []
            for result in results:
                if result.boxes is None:
                    continue
                for box in result.boxes:
                    x1, y1, x2, y2 = map(int, box.xyxy[0].tolist())
                    cls = int(box.cls[0])
                    conf = float(box.conf[0])
                    if cls in self.target_classes:
                        players.append({
                            'x': (x1 + x2) // 2,
                            'y': (y1 + y2) // 2,
                            'w': x2 - x1,
                            'h': y2 - y1,
                            'conf': conf,
                            'bbox': (x1, y1, x2, y2),
                            'center': (int((x1+x2)/2), int((y1+y2)/2))
                        })
            self._last_detection = players
            return players
        except Exception as e:
            logger.debug(f"YOLO detect error: {e}")
            return []
    
    def get_target(self, players: List[Dict], cx: int, cy: int) -> Optional[Dict]:
        if not players:
            return None
        best = None
        best_score = -1
        for player in players:
            dx = player['x'] - cx
            dy = player['y'] - cy
            dist = math.hypot(dx, dy)
            if dist < self.fov:
                score = (1 - dist / self.fov) * player['conf'] * 2
                if score > best_score:
                    best_score = score
                    best = player
        return best
    
    def aim_at(self, tx: int, ty: int, cx: int, cy: int) -> bool:
        dx = tx - cx
        dy = ty - cy
        if abs(dx) < 2 and abs(dy) < 2:
            return False
        smooth_factor = self.speed * 0.4
        move_x = dx * smooth_factor + random.uniform(-0.5, 0.5)
        move_y = dy * smooth_factor + random.uniform(-0.5, 0.5)
        max_step = 15
        move_x = max(-max_step, min(max_step, move_x))
        move_y = max(-max_step, min(max_step, move_y))
        win32api.mouse_event(win32con.MOUSEEVENTF_MOVE, int(move_x), int(move_y), 0, 0)
        return True

