class CombatExploits:
    """Все боевые эксплойты в одном классе"""
    
    def __init__(self, mem: MemoryManager):
        self.mem = mem
        self.shot_count = 0
        self.bhop_count = 0
        self.teleport_count = 0
        self.damage_dealt = 0
        self.kills = 0
        self._last_shot_time = 0
        self._last_jump_time = 0
        self._is_attacking = False
        
        logger.info("CombatExploits initialized")
    
    def force_jump(self) -> bool:
        """Принудительный прыжок (BunnyHop)"""
        current_time = time.time()
        if current_time - self._last_jump_time < 0.01:
            return False
        
        addr = self.mem.get_force_jump()
        if addr:
            self.mem.write_int(addr, 6)
            time.sleep(0.001)
            self.mem.write_int(addr, 4)
            self.bhop_count += 1
            self._last_jump_time = current_time
            return True
        return False
    
    def force_attack(self) -> bool:
        """Принудительный выстрел"""
        current_time = time.time()
        if current_time - self._last_shot_time < 0.05:
            return False
        
        addr = self.mem.get_force_attack()
        if addr:
            self.mem.write_int(addr, 5)
            time.sleep(0.001)
            self.mem.write_int(addr, 4)
            self.shot_count += 1
            self._last_shot_time = current_time
            return True
        return False
    
    def force_attack2(self) -> bool:
        """Принудительное прицеливание (ПКМ)"""
        addr = self.mem.get_force_attack2()
        if addr:
            self.mem.write_int(addr, 5)
            time.sleep(0.001)
            self.mem.write_int(addr, 4)
            return True
        return False
    
    def no_recoil(self) -> bool:
        """Убираем отдачу"""
        p = self.mem.local_player
        if not p:
            return False
        
        # aim_punch_angle
        self.mem.write_float(p + 0x32A8, 0.0)
        self.mem.write_float(p + 0x32A8 + 4, 0.0)
        # view_punch_angle
        self.mem.write_float(p + 0x32B0, 0.0)
        self.mem.write_float(p + 0x32B0 + 4, 0.0)
        return True
    
    def speed_hack(self, speed: float) -> bool:
        """Ускорение"""
        p = self.mem.local_player
        if not p:
            return False
        
        # m_flLaggedMovementValue
        self.mem.write_float(p + 0x33A4, speed)
        # m_flForwardSpeed
        self.mem.write_float(p + 0x33A8, speed * 450.0)
        # m_flSideSpeed
        self.mem.write_float(p + 0x33AC, speed * 450.0)
        return True
    
    def no_flash(self) -> bool:
        """Защита от флешек"""
        p = self.mem.local_player
        if not p:
            return False
        
        # m_flFlashDuration
        self.mem.write_float(p + 0x30A8, 0.0)
        # m_flFlashMaxAlpha
        self.mem.write_float(p + 0x30AC, 0.0)
        return True
    
    def radar_hack(self) -> bool:
        """Все на радаре"""
        if not self.mem.base_address:
            return False
        
        # m_bSpotted для всех врагов
        radar_base = self.mem.base_address + 0x17C2B40
        self.mem.write_int(radar_base, 1)
        return True
    
    def teleport(self, pos: Vector3) -> bool:
        """Телепорт"""
        p = self.mem.local_player
        if not p:
            return False
        
        self.mem.write_vec3(p + 0x138, pos)
        self.teleport_count += 1
        return True
    
    def wallshot(self, target_pos: Vector3) -> bool:
        """Wallshot - пуля сквозь стены (буквально через всю карту)"""
        p = self.mem.local_player
        if not p:
            return False
        
        origin = self.mem.get_origin(p)
        if not origin:
            return False
        
        dx = target_pos.x - origin.x
        dy = target_pos.y - origin.y
        dz = target_pos.z - origin.z
        dist = math.hypot(dx, dy, dz)
        if dist == 0:
            return False
        
        angle_addr = p + 0x134
        pitch = -math.degrees(math.asin(dz / dist))
        yaw = math.degrees(math.atan2(dy, dx))
        
        self.mem.write_float(angle_addr, yaw)
        self.mem.write_float(angle_addr + 4, pitch)
        
        # Увеличиваем пробитие до максимума
        self.mem.write_float(p + 0x3A4C, 999.0)  # m_flPenetration
        self.mem.write_float(p + 0x3A50, 999.0)  # m_flDamage
        
        time.sleep(0.01)
        self.force_attack()
        time.sleep(0.01)
        self.force_attack()
        return True
    
    def autowall(self, target_pos: Vector3) -> bool:
        """Autowall - пуля огибает углы (рикошет)"""
        p = self.mem.local_player
        if not p:
            return False
        
        origin = self.mem.get_origin(p)
        if not origin:
            return False
        
        # Генерируем случайное отклонение для имитации рикошета
        deviation = Vector3(
            random.uniform(-8, 8),
            random.uniform(-8, 8),
            random.uniform(-2, 2)
        )
        
        target = target_pos + deviation
        dx = target.x - origin.x
        dy = target.y - origin.y
        dz = target.z - origin.z
        dist = math.hypot(dx, dy, dz)
        if dist == 0:
            return False
        
        angle_addr = p + 0x134
        pitch = -math.degrees(math.asin(dz / dist))
        yaw = math.degrees(math.atan2(dy, dx))
        
        # Серия выстрелов с разными углами
        for offset in [-3, -1, 0, 1, 3]:
            self.mem.write_float(angle_addr, yaw + offset)
            self.mem.write_float(angle_addr + 4, pitch + offset * 0.3)
            time.sleep(0.005)
            self.force_attack()
        
        return True
    
    def spinbot(self, speed: int, direction: str = "right") -> bool:
        """Spinbot - крутилка"""
        p = self.mem.local_player
        if not p:
            return False
        
        angle_addr = p + 0x134
        current_yaw = self.mem.read_float(angle_addr)
        
        if direction == "right":
            new_yaw = current_yaw + speed * 0.1
        else:
            new_yaw = current_yaw - speed * 0.1
        
        self.mem.write_float(angle_addr, new_yaw)
        return True
    
    def triggerbot(self, target: Dict, delay: int = 50) -> bool:
        """Triggerbot - авто-выстрел при наведении"""
        if not target or target['conf'] < 0.6:
            return False
        
        time.sleep(delay / 1000)
        self.force_attack()
        return True

