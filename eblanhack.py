class Bot:
    def __init__(self, memory: MemoryManager, aimbot: YOLOAimbot):
        self.memory = memory
        self.aimbot = aimbot
        self.exploits = CombatExploits(memory)
        self.visuals = VisualSystem(memory)
        self.config = Config()
        self.is_running = False
        self.is_aiming = False
        self.is_shooting = False
        self.stats = {"fps": 0, "targets": 0, "shots": 0, "bhops": 0, "kills": 0, "damage": 0, "accuracy": 0.0, "start_time": time.time(), "last_shot": 0}
        self._enemies = []
        self._target = None
        self._frame_buffer = deque(maxlen=10)
        self._last_update = 0
        logger.info("Bot initialized")
    
    def update(self, frame: np.ndarray) -> bool:
        if not self.is_running:
            return False
        current_time = time.time()
        if current_time - self._last_update < 0.001:
            return True
        self._last_update = current_time
        try:
            local = self.memory.local_player
            if not local:
                return False
            self._enemies = self._collect_enemies(local)
            self._update_visuals()
            players = self.aimbot.detect(frame)
            target = self.aimbot.get_target(players, ScreenConstants.CENTER_X, ScreenConstants.CENTER_Y)
            self._execute_actions(local, target)
            self._update_stats()
            return True
        except Exception as e:
            logger.error(f"Bot update error: {e}")
            return False
    
    def _collect_enemies(self, local: int) -> List[Player]:
        enemies = []
        player_count = self.memory.get_player_count()
        local_team = self.memory.get_team(local)
        view_matrix = self.memory.read_matrix(self.memory.base_address + 0x17B0D30) if self.memory.base_address else None
        for i in range(1, min(player_count, 64)):
            entity = self.memory.get_entity(i)
            if not entity or entity == local:
                continue
            health = self.memory.get_health(entity)
            if health <= 0 or health > 100:
                continue
            team = self.memory.get_team(entity)
            if team == local_team:
                continue
            if self.memory.is_dormant(entity):
                continue
            pos = self.memory.get_origin(entity)
            origin = self.memory.get_origin(local)
            distance = origin.distance_to(pos)
            is_visible = True
            if view_matrix:
                screen_pos = MathUtils.world_to_screen(pos, view_matrix)
                is_visible = screen_pos is not None and 0 < screen_pos.x < ScreenConstants.WIDTH and 0 < screen_pos.y < ScreenConstants.HEIGHT
            player = Player(address=entity, health=health, team=team, position=pos, distance=distance, is_enemy=True, is_visible=is_visible, is_dormant=False, glow_index=self.memory.read_int(entity + 0x10428))
            enemies.append(player)
        return sorted(enemies, key=lambda p: p.distance)
    
    def _update_visuals(self):
        if self.config.glow:
            self.visuals.glow_enabled = True
            self.visuals.glow_color = self.config.glow_color
            self.visuals.glow_esp(self._enemies)
        else:
            self.visuals.glow_enabled = False
        if self.config.radar:
            self.visuals.radar_enabled = True
            self.visuals.radar_hack()
        else:
            self.visuals.radar_enabled = False
    
    def _execute_actions(self, local: int, target: Optional[Dict]):
        if not local:
            return
        if self.config.norecoil:
            self.exploits.no_recoil()
        if self.config.speed:
            self.exploits.speed_hack(self.config.speed_val)
        if self.config.noflash:
            self.exploits.no_flash()
        if self.config.bhop:
            self.exploits.force_jump()
        if self.config.wallshot and self._enemies:
            target_enemy = min(self._enemies, key=lambda e: e.distance)
            self.exploits.wallshot(target_enemy.position)
        if self.config.autowall and self._enemies:
            target_enemy = min(self._enemies, key=lambda e: e.distance)
            self.exploits.autowall(target_enemy.position)
        if self.config.aimbot and target:
            self.aimbot.fov = self.config.fov
            self.aimbot.speed = self.config.aim_speed
            self.aimbot.aim_at(target['x'], target['y'], ScreenConstants.CENTER_X, ScreenConstants.CENTER_Y)
            self.is_aiming = True
            self.stats["targets"] = len(self._enemies)
        else:
            self.is_aiming = False
        if self.config.trigger and target and target['conf'] > self.config.aim_confidence:
            time.sleep(self.config.trigger_delay / 1000)
            self.exploits.force_attack()
            self.is_shooting = True
            self.stats["shots"] += 1
        else:
            self.is_shooting = False
    
    def _update_stats(self):
        self.stats["bhops"] = self.exploits.bhop_count
    
    def get_stats(self) -> Dict:
        elapsed = time.time() - self.stats["start_time"]
        return {**self.stats, "elapsed": elapsed, "elapsed_str": f"{int(elapsed // 60):02d}:{int(elapsed % 60):02d}"}

