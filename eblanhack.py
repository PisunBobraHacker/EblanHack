class VisualSystem:
    """Система визуальных эффектов (Glow ESP, Radar, Overlay)"""
    
    def __init__(self, mem: MemoryManager):
        self.mem = mem
        self.glow_enabled = False
        self.radar_enabled = False
        self.overlay_enabled = False
        
        # Настройки Glow
        self.glow_color = (1.0, 0.0, 0.0, 1.0)
        self.glow_style = 1  # 0 = outline, 1 = full
        
        # Настройки Overlay
        self.overlay_opacity = 0.7
        self.overlay_color = (0, 255, 0)
        
        logger.info("VisualSystem initialized")
    
    def glow_esp(self, enemies: List[Player], color: Tuple[float, float, float, float] = None) -> bool:
        """Glow ESP для врагов"""
        if not self.glow_enabled:
            return False
        
        glow_manager = self.mem.get_glow_manager()
        if not glow_manager or not enemies:
            return False
        
        if color is None:
            color = self.glow_color
        
        for enemy in enemies:
            glow_index = self.mem.read_int(enemy.address + 0x10428)
            if glow_index < 0:
                continue
            
            glow_object = glow_manager + (glow_index * 0x38)
            r, g, b, a = color
            
            self.mem.write_float(glow_object + 0x4, r)    # Red
            self.mem.write_float(glow_object + 0x8, g)    # Green
            self.mem.write_float(glow_object + 0xC, b)    # Blue
            self.mem.write_float(glow_object + 0x10, a)   # Alpha
            self.mem.write_int(glow_object + 0x24, 1)     # Enable
            self.mem.write_int(glow_object + 0x28, self.glow_style)  # Style
        
        return True
    
    def radar_hack(self) -> bool:
        """Radar Hack - все видны на радаре"""
        if not self.radar_enabled:
            return False
        
        if not self.mem.base_address:
            return False
        
        radar_base = self.mem.base_address + 0x17C2B40
        self.mem.write_int(radar_base, 1)
        return True
    
    def draw_overlay(self, frame: np.ndarray, enemies: List[Player]) -> np.ndarray:
        """Отрисовка оверлея (Box ESP, Distance, Health)"""
        if not self.overlay_enabled or not enemies:
            return frame
        
        view_matrix = self.mem.read_matrix(self.mem.base_address + 0x17B0D30) if self.mem.base_address else None
        if not view_matrix:
            return frame
        
        for enemy in enemies:
            screen_pos = MathUtils.world_to_screen(enemy.position, view_matrix)
            if not screen_pos:
                continue
            
            x, y = int(screen_pos.x), int(screen_pos.y)
            
            # Box
            box_size = 50
            cv2.rectangle(frame, (x - box_size//2, y - box_size), 
                         (x + box_size//2, y + box_size//2), 
                         self.overlay_color, 2)
            
            # Health bar
            health_percent = enemy.health / 100.0
            bar_width = 40
            bar_height = 4
            bar_x = x - bar_width // 2
            bar_y = y - box_size - 10
            
            cv2.rectangle(frame, (bar_x, bar_y), (bar_x + bar_width, bar_y + bar_height), (50, 50, 50), -1)
            cv2.rectangle(frame, (bar_x, bar_y), (bar_x + int(bar_width * health_percent), bar_y + bar_height),
                         (0, int(255 * health_percent), 0), -1)
            
            # Distance
            cv2.putText(frame, f"{enemy.distance:.0f}m", (x - 15, y + box_size//2 + 20),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)
        
        return frame

