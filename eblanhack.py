    def _setup_keyboard_hotkeys(self):
        """Настройка горячих клавиш"""
        def on_press(key):
            try:
                if not self.bot.is_running:
                    return
                
                key_str = str(key).replace("'", "").lower()
                
                # Wallshot toggle
                if key_str == self.bot.config.wallshot_key:
                    self.bot.config.wallshot = not self.bot.config.wallshot
                    self.wallshot_var.set(self.bot.config.wallshot)
                    logger.debug(f"Wallshot: {self.bot.config.wallshot}")
                
                # Autowall toggle
                elif key_str == self.bot.config.autowall_key:
                    self.bot.config.autowall = not self.bot.config.autowall
                    self.autowall_var.set(self.bot.config.autowall)
                    logger.debug(f"Autowall: {self.bot.config.autowall}")
                
                # Triggerbot toggle
                elif key_str == self.bot.config.trigger_key:
                    self.bot.config.trigger = not self.bot.config.trigger
                    self.trigger_var.set(self.bot.config.trigger)
                    logger.debug(f"Trigger: {self.bot.config.trigger}")
                
                # Aimbot toggle (Alt)
                elif key_str == self.bot.config.aimbot_key:
                    self.bot.config.aimbot = not self.bot.config.aimbot
                    self.aimbot_var.set(self.bot.config.aimbot)
                    logger.debug(f"Aimbot: {self.bot.config.aimbot}")
                
                # Teleport (F7)
                elif key_str == "f7":
                    self.bot.config.teleport = not self.bot.config.teleport
                    self.teleport_var.set(self.bot.config.teleport)
                    logger.debug(f"Teleport: {self.bot.config.teleport}")
            except Exception as e:
                logger.debug(f"Hotkey error: {e}")
        
        self.keyboard_listener = keyboard.Listener(on_press=on_press)
        self.keyboard_listener.start()
        logger.info("Keyboard hotkeys enabled")
    
    def run(self):
        """Запуск GUI"""
        self.window.mainloop()

